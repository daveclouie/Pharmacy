<?php
require_once 'includes/auth.php';
require_once 'includes/xlsx.php';
require_login();

$titles = [
    'sales'     => 'Sales Report',
    'inventory' => 'Inventory Report',
    'movement'  => 'Stock Movement Report',
    'lowstock'  => 'Low-Stock Report',
    'expired'   => 'Expired & Near-Expiry Report',
];
$days = EXPIRY_WARNING_DAYS;

// ---- Generate: build the chosen report and download it as a CSV file (opens in Excel) ----
if (isset($_GET['generate'])) {
    $type = $_GET['type'] ?? 'sales';
    if (!isset($titles[$type])) $type = 'sales';

    // Date range fields differ per report
    $from = $to = '';
    if ($type === 'sales' || $type === 'movement') {
        $from = $_GET['from'] ?? date('Y-m-01');
        $to = $_GET['to'] ?? date('Y-m-d');
        if ($from === '' || $to === '' || $from > $to) {
            flash('Please choose a valid date range (From must not be after To).', 'error');
            header('Location: reports.php');
            exit;
        }
    } elseif ($type === 'expired') {
        $from = $_GET['exp_from'] ?? '';
        $to = $_GET['exp_to'] ?? '';
        if ($from !== '' && $to !== '' && $from > $to) {
            flash('Please choose a valid expiry range (From must not be after To).', 'error');
            header('Location: reports.php');
            exit;
        }
    }

    $suffix = date('Y-m-d');
    if ($type === 'sales' || $type === 'movement') {
        $suffix = "{$from}_to_{$to}";
    } elseif ($type === 'expired' && ($from !== '' || $to !== '')) {
        $suffix = 'expiring_' . ($from ?: 'start') . '_to_' . ($to ?: 'end');
    }
    $filename = 'ck_pharmacy_' . $type . '_report_' . $suffix . '.xlsx';
    $sheetNames = ['sales' => 'Sales Report', 'inventory' => 'Inventory', 'movement' => 'Stock Movement',
                   'lowstock' => 'Low Stock', 'expired' => 'Expiry'];

    $R = []; // rows for the Excel file
    $R[] = ['cells' => ['CK Pharmacy - ' . $titles[$type]], 'style' => 'title'];
    $R[] = ['cells' => ['Generated', date('Y-m-d H:i:s')], 'style' => 'meta'];
    $R[] = ['cells' => ['Generated by', $_SESSION['user']['full_name']], 'style' => 'meta'];

    if ($type === 'sales') {
        $R[] = ['cells' => ['Period', "$from to $to"], 'style' => 'meta'];
        $R[] = [];

        $s = $pdo->prepare('SELECT DATE(s.created_at) AS day, COUNT(DISTINCT s.id) AS transactions,
                                   SUM(si.qty) AS items, SUM(si.qty * si.price) AS revenue
                            FROM sales s JOIN sale_items si ON si.sale_id = s.id
                            WHERE DATE(s.created_at) BETWEEN ? AND ?
                            GROUP BY DATE(s.created_at) ORDER BY day');
        $s->execute([$from, $to]);
        $rows = $s->fetchAll();

        $R[] = ['cells' => ['Date', 'Transactions', 'Items Sold', 'Revenue'], 'style' => 'header'];
        $total = 0;
        foreach ($rows as $r) {
            $R[] = [$r['day'], (int)$r['transactions'], (int)$r['items'], xl_money($r['revenue'])];
            $total += $r['revenue'];
        }
        if (!$rows) $R[] = ['No sales in this period'];
        $R[] = ['cells' => ['TOTAL REVENUE', '', '', xl_money($total)], 'style' => 'total'];

        $s = $pdo->prepare('SELECT p.name, SUM(si.qty) AS qty, SUM(si.qty * si.price) AS revenue
                            FROM sale_items si JOIN sales s ON s.id = si.sale_id JOIN products p ON p.id = si.product_id
                            WHERE DATE(s.created_at) BETWEEN ? AND ?
                            GROUP BY p.id ORDER BY qty DESC LIMIT 10');
        $s->execute([$from, $to]);
        $top = $s->fetchAll();
        if ($top) {
            $R[] = [];
            $R[] = ['cells' => ['Top-Selling Products'], 'style' => 'section'];
            $R[] = ['cells' => ['Product', 'Units Sold', 'Revenue'], 'style' => 'header'];
            foreach ($top as $t) {
                $R[] = [$t['name'], (int)$t['qty'], xl_money($t['revenue'])];
            }
        }

    } elseif ($type === 'inventory') {
        $R[] = [];
        $rows = $pdo->query('SELECT p.name, p.category, s.name AS supplier, p.quantity, p.price, p.quantity * p.price AS value
                             FROM products p LEFT JOIN suppliers s ON s.id = p.supplier_id ORDER BY p.name')->fetchAll();
        $R[] = ['cells' => ['Product', 'Category', 'Supplier', 'Quantity', 'Price', 'Stock Value'], 'style' => 'header'];
        $total = 0;
        foreach ($rows as $r) {
            $R[] = [$r['name'], $r['category'], $r['supplier'] ?? '', (int)$r['quantity'],
                xl_money($r['price']), xl_money($r['value'])];
            $total += $r['value'];
        }
        $R[] = ['cells' => ['TOTAL STOCK VALUE', '', '', '', '', xl_money($total)], 'style' => 'total'];

    } elseif ($type === 'movement') {
        $R[] = ['cells' => ['Period', "$from to $to"], 'style' => 'meta'];
        $R[] = [];

        $s = $pdo->prepare('SELECT l.created_at, p.name, l.type, l.change_qty, l.note, u.full_name
                            FROM stock_log l
                            JOIN products p ON p.id = l.product_id
                            LEFT JOIN users u ON u.id = l.user_id
                            WHERE DATE(l.created_at) BETWEEN ? AND ?
                            ORDER BY l.created_at, l.id');
        $s->execute([$from, $to]);
        $log = $s->fetchAll();

        $labels = ['add' => 'Received', 'sale' => 'Sold', 'remove' => 'Removed', 'adjust' => 'Adjusted'];

        $summary = [];
        foreach ($log as $l) {
            $n = $l['name'];
            $summary[$n] = $summary[$n] ?? ['Received' => 0, 'Sold' => 0, 'Removed' => 0, 'Adjusted' => 0];
            $summary[$n][$labels[$l['type']] ?? 'Adjusted'] += abs($l['change_qty']);
        }
        ksort($summary);

        $R[] = ['cells' => ['Summary per Product'], 'style' => 'section'];
        $R[] = ['cells' => ['Product', 'Received', 'Sold', 'Removed', 'Net Change'], 'style' => 'header'];
        $tot = ['Received' => 0, 'Sold' => 0, 'Removed' => 0, 'Net' => 0];
        foreach ($summary as $name => $v) {
            $net = $v['Received'] - $v['Sold'] - $v['Removed'];
            $R[] = [$name, $v['Received'], $v['Sold'], $v['Removed'], $net];
            $tot['Received'] += $v['Received'];
            $tot['Sold'] += $v['Sold'];
            $tot['Removed'] += $v['Removed'];
            $tot['Net'] += $net;
        }
        if (!$summary) $R[] = ['No stock movements in this period'];
        $R[] = ['cells' => ['TOTAL', $tot['Received'], $tot['Sold'], $tot['Removed'], $tot['Net']], 'style' => 'total'];

        $R[] = [];
        $R[] = ['cells' => ['Movement Details'], 'style' => 'section'];
        $R[] = ['cells' => ['Date & Time', 'Product', 'Movement', 'Quantity Change', 'Note', 'Recorded By'], 'style' => 'header'];
        foreach ($log as $l) {
            $R[] = [$l['created_at'], $l['name'], $labels[$l['type']] ?? $l['type'],
                (int)$l['change_qty'], (string)$l['note'], $l['full_name'] ?? ''];
        }

    } elseif ($type === 'lowstock') {
        $R[] = [];
        $rows = $pdo->query('SELECT p.name, s.name AS supplier, p.quantity, p.min_stock
                             FROM products p LEFT JOIN suppliers s ON s.id = p.supplier_id
                             WHERE p.quantity <= p.min_stock ORDER BY p.quantity')->fetchAll();
        $R[] = ['cells' => ['Product', 'Supplier', 'Quantity', 'Minimum Stock'], 'style' => 'header'];
        foreach ($rows as $r) {
            $R[] = [$r['name'], $r['supplier'] ?? '', (int)$r['quantity'], (int)$r['min_stock']];
        }
        if (!$rows) $R[] = ['No low-stock products'];

    } else { // expired
        if ($from !== '' || $to !== '') {
            $R[] = ['cells' => ['Expiry date range', ($from ?: 'any') . ' to ' . ($to ?: 'any')], 'style' => 'meta'];
        } else {
            $R[] = ['cells' => ['Scope', "Expired products and those expiring within $days days"], 'style' => 'meta'];
        }
        $R[] = [];

        $sql = "SELECT name, quantity, expiry_date,
                       CASE WHEN expiry_date < CURDATE() THEN 'Expired'
                            WHEN expiry_date <= DATE_ADD(CURDATE(), INTERVAL $days DAY) THEN 'Near expiry'
                            ELSE 'Not near expiry' END AS status
                FROM products WHERE expiry_date IS NOT NULL";
        $params = [];
        if ($from !== '' || $to !== '') {
            if ($from !== '') { $sql .= ' AND expiry_date >= ?'; $params[] = $from; }
            if ($to !== '')   { $sql .= ' AND expiry_date <= ?'; $params[] = $to; }
        } else {
            $sql .= " AND expiry_date <= DATE_ADD(CURDATE(), INTERVAL $days DAY)";
        }
        $sql .= ' ORDER BY expiry_date';
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        $rows = $stmt->fetchAll();

        $R[] = ['cells' => ['Product', 'Quantity', 'Expiry Date', 'Status'], 'style' => 'header'];
        foreach ($rows as $r) {
            $R[] = [$r['name'], (int)$r['quantity'], $r['expiry_date'], $r['status']];
        }
        if (!$rows) $R[] = ['No products found'];
    }

    if (!xlsx_send($R, $sheetNames[$type], $filename)) {
        flash('Could not create the Excel file. In XAMPP, open php.ini and make sure "extension=zip" is enabled, then restart Apache.', 'error');
        header('Location: reports.php');
    }
    exit;
}

