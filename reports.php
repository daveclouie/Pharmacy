<script>
const notes = {
    sales: 'Sales made within the chosen dates.',
    movement: 'Items received, sold, and removed within the chosen dates.',
    expired: 'Products whose expiration date falls in this range, e.g. Nov 1 to Dec 31. Leave both blank to list all expired products and those expiring within <?= $days ?> days.',
    inventory: 'Shows the current stock of every product. No date range is needed.',
    lowstock: 'Shows the current low-stock products. No date range is needed.'
};
const typeSel = document.getElementById('reportType');
function toggleRanges() {
    const t = typeSel.value;
    const tx = (t === 'sales' || t === 'movement');
    document.querySelectorAll('.range-tx').forEach(el => {
        el.style.display = tx ? '' : 'none';
        el.querySelector('input').disabled = !tx;
    });
    document.querySelectorAll('.range-exp').forEach(el => {
        el.style.display = (t === 'expired') ? '' : 'none';
        el.querySelector('input').disabled = (t !== 'expired');
    });
    document.getElementById('rangeNote').textContent = notes[t] || '';
}
typeSel.addEventListener('change', toggleRanges);
toggleRanges();
</script>
